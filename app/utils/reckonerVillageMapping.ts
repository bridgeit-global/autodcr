/** English form key → Marathi reckoner key (first match when multiple Marathi map to same English). */
export const ENGLISH_TO_MARATHI_VILLAGE: Record<string, string> = Object.fromEntries(
  Object.entries(MARATHI_TO_ENGLISH_VILLAGE).map(([marathi, english]) => [english, marathi])
);

export function englishVillageToMarathi(englishVillage: string): string | null {
  const key = englishVillage.trim().toUpperCase().replace(/\s+/g, " ");
  // Direct lookup (case-insensitive)
  for (const [marathi, english] of Object.entries(MARATHI_TO_ENGLISH_VILLAGE)) {
    if (english.toUpperCase() === key) return marathi;
  }
  // Normalize common variants: BANDRA - A → BANDRA-A
  const normalized = key.replace(/\s*-\s*/g, "-").replace(/\s+/g, " ");
  for (const [marathi, english] of Object.entries(MARATHI_TO_ENGLISH_VILLAGE)) {
    const engNorm = english.toUpperCase().replace(/\s*-\s*/g, "-").replace(/\s+/g, " ");
    if (engNorm === normalized) return marathi;
  }
  return ENGLISH_TO_MARATHI_VILLAGE[key] ?? null;
}

export function marathiVillageToEnglish(marathiVillage: string): string | null {
  return MARATHI_TO_ENGLISH_VILLAGE[marathiVillage.trim()] ?? null;
}
